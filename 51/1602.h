/*
 * 文件名: 1602.h
 * 功  能: LCD1602 字符型液晶显示屏驱动（内联实现头文件）
 *         LCD1602 是一款标准 16×2 字符液晶显示模块，采用并口（4位或8位）通信。
 *         本驱动使用8位并口模式，控制引脚连接到 P2 口，数据引脚连接到 P1 口。
 *
 * 引脚连接：
 *   RS  → P2.5    寄存器选择：0=指令寄存器，1=数据寄存器
 *   RW  → P2.6    读写选择：0=写操作，1=读操作（本驱动只写，始终保持为0）
 *   E   → P2.7    使能信号：高电平有效，下降沿触发 LCD 采样数据
 *   D0~D7 → P1    8位数据总线
 */

/* ---- 控制引脚定义 ---- */
sbit  RS=P2^5;              /* 寄存器选择引脚（Register Select） */
sbit  RWW=P2^6;             /* 读写控制引脚（Read/Write） */
sbit  E=P2^7;               /* 使能引脚（Enable） */

/* ---- 控制引脚操作宏，简化代码书写 ---- */
#define e1   E=1            /* 使能引脚置高（使能有效） */
#define rd1  RWW=1          /* 读写引脚置高（读模式） */
#define rs1  RS=1           /* 寄存器选择置高（数据寄存器） */
#define e0   E=0            /* 使能引脚置低（使能无效，产生下降沿触发） */
#define rd0  RWW=0          /* 读写引脚置低（写模式） */
#define rs0  RS=0           /* 寄存器选择置低（指令寄存器） */

/* 8位数据总线端口 */
#define PP P1

/*
 * 函数名: _delay_ms
 * 功  能: 毫秒级软件延时
 * 参  数: t — 延时毫秒数（11.0592 MHz 下每毫秒约循环120次）
 */
void _delay_ms(uint t)
{
   uint i,j;
   for(i=0;i<t;i++)
     for(j=0;j<120;j++);
}

/*
 * 函数名: _delay_us
 * 功  能: 微秒级软件延时（粗略，适用于 LCD 时序要求较宽松的场景）
 * 参  数: t — 循环次数，近似代表微秒数
 */
void _delay_us(uchar t)
{
   while(t>0)t--;
} 

/*
 * 函数名: lcd1602_writecrtl
 * 功  能: 向 LCD1602 写入一个指令字节（RS=0，RW=0，发送控制命令）
 *         时序：RW=0 → RS=0 → 写数据到 P1 → E=1（使能） → E=0（下降沿触发）
 * 参  数: dat — 要写入的指令字节（如 0x38 初始化指令、0x01 清屏指令等）
 */
void  lcd1602_writecrtl(uchar  dat)
{
  rd0;                      /* RW=0，选择写操作 */
  rs0;                      /* RS=0，选择指令寄存器 */
  _delay_us(5);
  PP=dat;                   /* 将指令字节送到数据总线 P1 */
  e1;                       /* E 置高，使能有效，LCD 开始采样 */
  _delay_us(5);
  e0;                       /* E 置低，产生下降沿，LCD 锁存并执行指令 */
}

/*
 * 函数名: lcd1602_writenumber
 * 功  能: 向 LCD1602 写入一个数据字节（RS=1，RW=0，写显示数据）
 *         时序与写指令类似，但 RS=1 表示写入的是要显示的字符数据
 * 参  数: dat — 要显示的字符的 ASCII 码（如 '0'=0x30 表示字符"0"）
 */
void  lcd1602_writenumber(uchar dat)
{
  rd0;                      /* RW=0，选择写操作 */
  rs1;                      /* RS=1，选择数据寄存器（写显示内容） */
  _delay_us(5);
  PP=dat;                   /* 将字符的 ASCII 码送到数据总线 */
  e1;                       /* E 置高，使能有效 */
  _delay_us(5);
  e0;                       /* E 置低，下降沿触发，字符写入显存 */
}

/*
 * 函数名: lcd1602_init
 * 功  能: 初始化 LCD1602 为常用显示模式
 *         初始化顺序（符合 HD44780 控制器规范）：
 *           1. 0x38：8位数据接口，2行显示，5×8点阵字符
 *           2. 0x06：写入数据后光标右移，屏幕不移动
 *           3. 0x0C：开显示，关光标，光标不闪烁
 *           4. 0x01：清屏，光标归位（地址清零）
 */
void  lcd1602_init()  
{
  lcd1602_writecrtl(0x38);  /* 功能设置：8位并口，双行，5×8字符 */
  lcd1602_writecrtl(0x06);  /* 输入模式：写入后光标右移，画面不移动 */
  lcd1602_writecrtl(0x0c);  /* 显示控制：显示开，光标关，不闪烁 */
  lcd1602_writecrtl(0x01);  /* 清屏：清除所有显示内容，光标回原点 */
}

/*
 * 函数名: lcd1602_adr
 * 功  能: 设置 LCD1602 的显示数据内存（DDRAM）写入地址
 *         地址规则：第1行地址 0x00~0x0F；第2行地址 0x40~0x4F
 *         调用后下一次写入的字符将出现在该地址对应的位置
 * 参  数: dat — DDRAM 地址偏移（0x00~0x0F 为第1行，0x40~0x4F 为第2行）
 */
void  lcd1602_adr(uchar dat)  
{
  lcd1602_writecrtl(0x80 | dat);  /* 指令 0x80 | 地址，写 DDRAM 地址设置命令 */
}

/*
 * 函数名: LCD1602_string
 * 功  能: 在 LCD1602 的指定行列位置起始，显示一个字符串
 * 参  数: hang — 行号（1=第一行，2=第二行）
 *         lie  — 列号（1~16，从1开始计数）
 *         p    — 指向要显示的字符串的指针（以 '\0' 结尾）
 */
void LCD1602_string(uchar hang,uchar lie,uchar const *p)
{
    uchar a;
    if(hang == 1) a = 0x00;         /* 第1行起始 DDRAM 地址为 0x00 */
    if(hang == 2) a = 0x40;         /* 第2行起始 DDRAM 地址为 0x40 */
    a = a + lie - 1;                /* 加上列偏移（列从1开始，所以减1） */
    lcd1602_adr(a);                 /* 定位到目标地址 */
    while(1)
    {
        if(*p == '\0') break;       /* 遇到字符串结束符，停止输出 */
        lcd1602_writenumber(*p);     /* 逐字符写入显存 */
        p++;                         /* 移动到下一个字符 */
    }
}
