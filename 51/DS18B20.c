/*
 * 文件名: DS18B20.c
 * 功  能: DS18B20 数字温度传感器驱动实现
 *         遵循 Dallas 1-Wire 单总线协议，实现对 DS18B20 的初始化（复位应答）、
 *         字节写入、字节读取、启动温度转换以及读取温度数值等操作。
 * 数据引脚: DQ1 = P2.0（在 DS18B20.h 中定义）
 */

#include<DS18B20.h>

/*
 * 函数名: delays
 * 功  能: 软件延时函数，利用循环空转消耗 CPU 时间
 *         在 11.0592 MHz 晶振、未优化编译条件下，每次循环约 11 µs
 * 参  数: x — 循环次数（每次约 11 µs，x=1 约延时 11 µs）
 */
void delays(uint x)
{
    while( x-- );
}

/*
 * 函数名: DS18B20_rst1
 * 功  能: DS18B20 复位与存在脉冲检测（1-Wire 初始化时序）
 *         流程：
 *           1. 主机拉低总线 ≥480 µs（复位脉冲）
 *           2. 释放总线，等待 15~60 µs
 *           3. DS18B20 拉低总线 60~240 µs（存在脉冲），表示设备在线
 *           4. 等待存在脉冲结束后函数返回，总线恢复为高电平
 *         若未检测到存在脉冲，函数将继续重试直到检测成功。
 */
void DS18B20_rst1()
{
    bit flag=1;                 /* 存在脉冲检测标志，置1表示尚未检测到设备 */
    while( flag )
    {
        while( flag )
        {
            DQ1=1;
            delays(1);          /* 稍作延时，确保总线稳定 */
            DQ1=0;
            delays(50);         /* 拉低总线约 550 µs（满足 ≥480 µs 复位要求） */
            DQ1=1;              /* 释放总线（拉高），等待 DS18B20 应答 */
            delays(6);          /* 等待约 66 µs，此时 DS18B20 开始拉低总线 */
            flag=DQ1;           /* 读取总线状态：0=检测到存在脉冲，1=未检测到 */
        }
        delays(45);             /* 等待约 500 µs，确保存在脉冲已结束 */
        flag=~DQ1;              /* 再次验证：总线已释放（高电平）时 flag=0，退出循环 */
    }
    DQ1=1;                      /* 确保总线回到高电平空闲状态 */
}

/*
 * 函数名: DS18B20_write_byte1
 * 功  能: 向 DS18B20 写入一个字节（8位），低位先发（LSB First）
 *         每个位的写时序：
 *           - 写"0"：拉低总线 ≥60 µs
 *           - 写"1"：拉低总线后立即释放，≤15 µs 内释放
 * 参  数: byte — 待写入的字节数据
 */
void DS18B20_write_byte1(uchar byte)
{
    uchar i;
    for(i=0;i<8;i++)
    {
        DQ1=1;
        _nop_();                /* 1 个 NOP 保证信号稳定 */
        DQ1=0;                  /* 拉低总线，开始写时序 */
        NOPS();                 /* 约 4 µs，满足写"1"的时序窗口下限 */
        DQ1=byte&0x01;          /* 输出当前最低位：1=释放总线，0=保持拉低 */
        delays(6);              /* 约 66 µs，保证写时序完整 */
        byte>>=1;               /* 右移一位，准备发送下一位 */
    }
    DQ1=1;                      /* 一个字节发送完毕，释放总线 */
    delays(1);                  /* 短暂延时，给总线恢复时间 */
}

/*
 * 函数名: DS18B20_read_byte1
 * 功  能: 从 DS18B20 读取一个字节（8位），低位先接收（LSB First）
 *         每个位的读时序：
 *           - 主机拉低总线 ≥1 µs，然后释放
 *           - 在拉低后 15 µs 内采样总线电平
 * 返回值: 读取到的字节数据
 */
uchar DS18B20_read_byte1()
{
    uchar i,date=0;
    for(i=0;i<8;i++)
    {
        DQ1=1;
        _nop_();                /* 确保总线空闲 */
        date>>=1;               /* 先右移，为最高位腾出接收位置 */
        DQ1=0;
        NOPS();                 /* 拉低约 4 µs，启动读时序 */
        DQ1=1;                  /* 释放总线，由 DS18B20 驱动数据 */
        NOPS();                 /* 等待约 4 µs 后采样（在 15 µs 窗口内） */
        if(DQ1)
        {
            date |=0x80;        /* 采样为高电平，将最高位置1（因为是 LSB First） */
        }
        delays(6);              /* 约 66 µs，等待本位读时序结束 */
    }
    DQ1=1;                      /* 读取完毕，释放总线 */
    
    return date;
}

/*
 * 函数名: DS18B20_start_change1
 * 功  能: 向 DS18B20 发出温度转换命令，启动一次温度采样
 *         命令序列：复位 → 跳过ROM(0xCC) → 开始温度转换(0x44)
 *         温度转换需要一定时间（12位分辨率最长 750 ms），
 *         调用此函数后需等待转换完成再调用读取函数。
 */
void DS18B20_start_change1()
{
    DS18B20_rst1();                         /* 发送复位脉冲并等待存在应答 */
    DS18B20_write_byte1(0xcc);              /* 发送跳过ROM命令（总线上只有一个DS18B20时使用） */
    DS18B20_write_byte1(0x44);              /* 发送温度转换命令，DS18B20开始采集温度 */
}

/*
 * 函数名: DS18B20_read_date1
 * 功  能: 从 DS18B20 暂存器中读取温度转换结果，并以整数℃返回
 *         命令序列：复位 → 跳过ROM(0xCC) → 读暂存器(0xBE) → 读2字节温度数据
 *         温度数据格式（12位分辨率）：
 *           - Byte0：温度低8位（包含4位小数位）
 *           - Byte1：温度高8位（包含符号位）
 *         将 16 位数据右移4位去掉小数部分，得到整数℃。
 * 返回值: 温度整数值（℃），如 25 表示 25℃
 */
int DS18B20_read_date1()
{
    int temp;
    uchar date[2];                          /* 存放从 DS18B20 读取的2字节温度原始数据 */

    DS18B20_rst1();                         /* 发送复位脉冲 */

    DS18B20_write_byte1(0xcc);              /* 跳过 ROM 匹配（单个设备时直接跳过） */
    DS18B20_write_byte1(0xbe);              /* 发送读暂存器命令 */

    date[0]=DS18B20_read_byte1();           /* 读取温度低8位（LSByte，含4位小数） */
    date[1]=DS18B20_read_byte1();           /* 读取温度高8位（MSByte，含符号位） */

    temp=date[1];                           /* 将高字节放入 int 的高8位 */
    temp<<=8;
    temp |= date[0];                        /* 合并低字节，得到完整的16位温度原始值 */
    temp>>=4;                               /* 右移4位，去掉小数部分，保留整数℃ */

    return temp;
}
