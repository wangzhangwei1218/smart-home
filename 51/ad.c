sbit Clk2  = P3^3;
sbit DATI2 = P3^4; /* MCU -> ADC (DIN) */
sbit DATO2 = P3^2; /* ADC -> MCU (DOUT)  <-- ??????,??? DATI2 ?? */
sbit CS2   = P3^5;

/* ?????? */
static void clk_pulse(void)
{
    Clk2 = 1;
    _nop_(); _nop_();
    Clk2 = 0;
    _nop_(); _nop_();
}

void adc0832_init(void)
{
    CS2 = 1;     /* ???????? */
    Clk2 = 0;
    DATI2 = 0;
}

/*
  ? ADC0832 ???? CH (0 ? 1)
  ?? 0..255(unsigned int)
  ?????? ADC0832 ??:??? start + sgl + odd,??? 8 ?(???)?
  ?????????????????;??????????????(adval)?
*/
unsigned int adc08322(unsigned char CH)
{
    unsigned char i;
    unsigned char adval = 0;
    unsigned char test = 0;
    unsigned int result = 0;

    /* ???? */
    CS2 = 0;
    Clk2 = 0;
    _nop_();

    /* Start bit = 1 */
    DATI2 = 1;
    clk_pulse();

    /* SGL = 1 (single-ended), ODD = CH */
    DATI2 = 1; clk_pulse();               /* SGL=1 */
    DATI2 = (CH ? 1 : 0); clk_pulse();    /* ODD = channel */

    /* ?? datasheet ?????????? */
    DATI2 = 0;
    clk_pulse();

    /* ????? 8 ? (???) */
    adval = 0;
    for (i = 0; i < 8; i++) {
        Clk2 = 1;
        _nop_();
        adval <<= 1;
        if (DATO2) adval |= 0x01;
        Clk2 = 0;
        _nop_();
    }

    /* ????? 8 ????(??) */
    test = 0;
    for (i = 0; i < 8; i++) {
        Clk2 = 1;
        _nop_();
        test <<= 1;
        if (DATO2) test |= 0x01;
        Clk2 = 0;
        _nop_();
    }

    /* ???? */
    CS2 = 1;

    /* ??:??????????? test(??? adval);??? adval ?? */
    if (adval == test) result = adval;
    else result = adval; /* ????????????,???????? test */

    return (result & 0xFF);
}